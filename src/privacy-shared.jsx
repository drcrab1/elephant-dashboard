// 모든 문서/기록의 날짜는 서버 시간(serverTimestamp)으로만 기록합니다. (날짜 소급 입력 기능 없음)
export const serverTs = () => firebase.firestore.FieldValue.serverTimestamp();

export const toDate = (v) => {
    if (!v) return null;
    if (typeof v.toDate === 'function') return v.toDate();
    const d = new Date(v);
    return isNaN(d.getTime()) ? null : d;
};
const p2 = (n) => String(n).padStart(2, '0');
export const fmtDate = (v) => {
    const d = toDate(v);
    return d ? `${d.getFullYear()}.${p2(d.getMonth() + 1)}.${p2(d.getDate())}` : '-';
};
export const fmtDateTime = (v) => {
    const d = toDate(v);
    return d ? `${d.getFullYear()}.${p2(d.getMonth() + 1)}.${p2(d.getDate())} ${p2(d.getHours())}:${p2(d.getMinutes())}` : '-';
};

// 출력·내보내기 시 개인정보 표시 항목을 최소화하기 위한 마스킹 (기본값: 마스킹)
export const maskPhone = (v) => {
    const d = String(v || '').replace(/[^0-9]/g, '');
    if (d.length < 8) return v ? '***' : '';
    return `${d.slice(0, 3)}-****-${d.slice(-4)}`;
};
export const maskEmail = (v) => {
    const [id, host] = String(v || '').split('@');
    if (!host) return v || '';
    return `${id.slice(0, 2)}***@${host}`;
};

export const exportXlsx = (rows, sheetName, filename, note = '') => {
    logAccess('export', `${filename}${note ? ' (' + note + ')' : ''}`);
    const ws = XLSX.utils.json_to_sheet(rows.length ? rows : [{}]);
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, sheetName.slice(0, 30));
    XLSX.writeFile(wb, filename);
};

export const downloadBlob = (blob, filename) => {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 2000);
};

// DOM 노드 → A4 여러 페이지 PDF (기존 안전보건/계약 모듈과 동일한 html-to-image + jsPDF 방식)
const nodeToPdfBlob = async (el) => {
    const w = el.offsetWidth;
    const h = el.offsetHeight;
    // 아주 긴 문서도 모바일 캔버스 한도를 넘지 않게 해상도를 조절
    const pixelRatio = Math.max(1, Math.min(2, Math.sqrt(12e6 / (w * h))));
    const dataUrl = await toJpeg(el, {
        quality: 0.95,
        pixelRatio,
        backgroundColor: '#ffffff',
        style: { transform: 'none', opacity: '1', visibility: 'visible' },
    });
    const pdf = new jsPDF('p', 'mm', 'a4');
    const pageH = 297;
    const imgW = 210;
    const imgH = (h * imgW) / w;
    let left = imgH;
    let pos = 0;
    pdf.addImage(dataUrl, 'JPEG', 0, pos, imgW, imgH, undefined, 'FAST');
    left -= pageH;
    while (left > 1) {
        pos = left - imgH;
        pdf.addPage();
        pdf.addImage(dataUrl, 'JPEG', 0, pos, imgW, imgH, undefined, 'FAST');
        left -= pageH;
    }
    return pdf.output('blob');
};

// React 엘리먼트를 화면 밖에서 렌더링한 뒤 PDF Blob으로 변환
export const reactToPdfBlob = async (element) => {
    const host = document.createElement('div');
    host.style.cssText = 'position:fixed;left:-10000px;top:0;width:794px;background:#fff;';
    document.body.appendChild(host);
    const root = createRoot(host);
    try {
        flushSync(() => root.render(element));
        if (document.fonts && document.fonts.ready) await document.fonts.ready;
        await Promise.all(Array.from(host.querySelectorAll('img')).map((img) => (img.decode ? img.decode().catch(() => {}) : Promise.resolve())));
        return await nodeToPdfBlob(host.firstElementChild);
    } finally {
        root.unmount();
        host.remove();
    }
};

